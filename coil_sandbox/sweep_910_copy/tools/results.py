"""Summarise whatever the sweep has produced so far.

    python tools/results.py              # table to stdout
    python tools/results.py --md RESULTS.md
    python tools/results.py --csv results.csv

Reads `runs/<tag>/adjudication.json`, which `run_sweep.py` writes after every solve.
A point with no adjudication is `pending`; a point whose solve died leaves a log and no
adjudication, and shows up the same way -- check `runs/<tag>.log`.

READING THE NUMBERS, the three that have bitten this campaign:

* `bn` is `normalized_BdotN` on the run's own converged source grid. Never quote the
  `paper_metrics` default-grid value, which reads up to 60x high on a contorted arc.
* **`linked` is a hard rejection, not a note.** It comes from the pairwise MATRIX. Two
  points in this campaign were banked as improvements that turned out to BE the linking.
  A warm start's flux gain is not a result until this reads 0.
* `length` is judged against the SWEPT bound, every other margin against the paper bound.
  Margins below 1.000 are satisfied for length/kappa/kappa_MS; above 1.000 for d_cc/d_pc.
"""

import os as _os, sys as _sys  # noqa: E402
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import _bundle  # noqa: E402,F401  -- MUST precede any `import desc`

import argparse  # noqa: E402
import json  # noqa: E402
import os  # noqa: E402
import sys  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sweep_configs import points  # noqa: E402

UP = ("length", "kappa", "kappa_MS")   # satisfied when margin <= 1
LO = ("d_cc", "d_pc")                  # satisfied when margin >= 1


def rows():
    out = []
    for p in points():
        rec = None
        f = os.path.join(ROOT, p["out_dir"], "adjudication.json")
        if os.path.exists(f):
            try:
                rec = json.load(open(f))
            except Exception:
                rec = None
        out.append((p, rec))
    return out


def verdict(rec):
    if rec is None:
        return "pending"
    if rec["linking"]["n_linked_pairs"]:
        return f"VOID linked×{rec['linking']['n_linked_pairs']}"
    bad = [k for k in rec.get("failed", []) if k != "length"]
    return "ok" if not bad else "FAILS " + ",".join(bad)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--md", metavar="OUT", default=None)
    ap.add_argument("--csv", metavar="OUT", default=None)
    a = ap.parse_args()
    rs = rows()
    done = sum(1 for _, r in rs if r is not None)

    hdr = ["run", "rep", "xL", "L (m)", "bn", "max|B.n|/|B|",
           "length", "kappa", "kappa_MS", "d_cc", "d_pc", "linked", "verdict"]
    body = []
    for p, rec in rs:
        if rec is None:
            body.append([p["id"], p["rep"], f"{p['mult']:g}", f"{p['length_max']:.4f}"]
                        + ["—"] * 8 + ["pending"])
            continue
        m = rec["margins"]
        body.append([
            p["id"], p["rep"], f"{p['mult']:g}", f"{p['length_max']:.4f}",
            f"{rec['normalized_BdotN']:.4e}", f"{rec['max_BdotN_over_B']:.3e}",
            *[f"{m[k]:.3f}" for k in ("length", "kappa", "kappa_MS", "d_cc", "d_pc")],
            str(rec["linking"]["n_linked_pairs"]), verdict(rec),
        ])

    if a.csv:
        import csv
        with open(a.csv, "w", newline="") as fh:
            w = csv.writer(fh); w.writerow(hdr); w.writerows(body)
        print(f"wrote {a.csv}")
    if a.md:
        L = [f"# Sweep results ({done}/{len(rs)} runs adjudicated)", "",
             "Generated by `python tools/results.py --md`. Margins: `length`, `kappa`,",
             "`kappa_MS` are satisfied **below** 1.000; `d_cc`, `d_pc` **above** 1.000.",
             "`length` is judged against the swept bound, the rest against the paper",
             "bounds. **`linked` above 0 voids the point** — its `bn` is meaningless.", "",
             "| " + " | ".join(hdr) + " |",
             "|" + "---|" * len(hdr)]
        L += ["| " + " | ".join(r) + " |" for r in body]
        open(a.md, "w").write("\n".join(L) + "\n")
        print(f"wrote {a.md}")
    if not a.csv and not a.md:
        w = [max(len(hdr[i]), max((len(r[i]) for r in body), default=0))
             for i in range(len(hdr))]
        print("  ".join(h.ljust(w[i]) for i, h in enumerate(hdr)))
        print("  ".join("-" * w[i] for i in range(len(hdr))))
        for r in body:
            print("  ".join(c.ljust(w[i]) for i, c in enumerate(r)))
    print(f"\n{done}/{len(rs)} adjudicated"
          + (f", {sum(1 for _, r in rs if r and r['linking']['n_linked_pairs'])} VOID"
             if done else ""))


if __name__ == "__main__":
    main()
